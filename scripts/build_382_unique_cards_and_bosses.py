def extract_palette(im: Image.Image) -> list[str]:
    small = im.resize((24, 24), Image.Resampling.BILINEAR).quantize(colors=5)
    pal_raw = small.getpalette()[:15]
    cols = []
    for i in range(0, len(pal_raw), 3):
        cols.append(f"#{pal_raw[i]:02X}{pal_raw[i+1]:02X}{pal_raw[i+2]:02X}")
    while len(cols) < 5:
        cols.append("#334155")
    return cols[:5]


def main():
    mf = json.loads(MANIFEST_JSON.read_text(encoding="utf-8"))
    chars_by_faction: dict[str, list[dict]] = {}
    for ch in mf["characters"]:
        chars_by_faction.setdefault(ch["faction"], []).append(ch)
    for fac in chars_by_faction:
        chars_by_faction[fac].sort(key=lambda x: x["id"])

    hs_data = json.loads(HS_CARDS_JSON.read_text(encoding="utf-8"))
    st_data = json.loads(STONE_CARDS_JSON.read_text(encoding="utf-8"))
    st_by_id = {c["id"]: c for c in st_data["cards"]}

    cards = hs_data["cards"]
    assert len(cards) == 382, f"Expected 382 cards, got {len(cards)}"

    # 1. Process 9 Factions × 25 Cards (10 Original + 15 Newly Recruited = 25 Unique per Faction)
    recruited_char_id = 111  # NO.111 .. NO.245 (135 newly recruited faction characters!)

    for cls in ["PRIEST", "MAGE", "WARRIOR", "HUNTER", "PALADIN", "ROGUE", "SHAMAN", "WARLOCK", "DRUID"]:
        fac_key, fac_ko, realm_ko = CLASS_TO_FACTION[cls]
        orig_10 = chars_by_faction[fac_key]
        assert len(orig_10) == 10, f"Expected 10 chars for {fac_key}"

        cls_cards = [c for c in cards if c["cardClass"] == cls]
        assert len(cls_cards) == 25, f"Expected 25 cards for {cls}"

        ranked = sorted(
            cls_cards,
            key=lambda c: (
                0 if c["rarity"] == "LEGENDARY" else (1 if c["type"] == "MINION" else (2 if c["type"] == "WEAPON" else 3)),
                -c["cost"],
                c["id"],
            ),
        )
        keep10 = ranked[:10]
        new15 = ranked[10:]

        # Assign the 10 original faction characters strictly 1-to-1 (zero duplicates!)
        # Put the Hero representative (last in orig_10 or Legendary) on the Legendary card first!
        ordered_orig = list(reversed(orig_10))
        for idx, card in enumerate(keep10):
            ch = ordered_orig[idx]
            orig_hs = st_by_id.get(card["id"], {})
            orig_hs_name = orig_hs.get("name", card["name"])

            if card["type"] == "MINION":
                title_prefix = ch["novelRoleKo"].split()[0] if ch.get("novelRoleKo") else fac_ko
                card["name"] = f"{title_prefix} {ch['nameKo']}"[:15]
            elif card["type"] == "WEAPON":
                card["name"] = f"{ch['nameKo']}의 성물 병기" if len(orig_hs_name) > 8 else f"{ch['nameKo']}의 {orig_hs_name}"
            else:
                card["name"] = f"{ch['nameKo']}의 {orig_hs_name}"

            card["snsCharId"] = ch["id"]
