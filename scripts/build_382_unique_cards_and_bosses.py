def slice_5x3_sheet(sheet_path: Path, out_size: tuple[int, int] = (384, 384)) -> list[Image.Image]:
    im = Image.open(sheet_path).convert("RGB")
    arr = np.asarray(im, dtype=np.float32)
    w, h = im.size
    col_lum = arr.mean(axis=(0, 2))
    row_lum = arr.mean(axis=(1, 2))

    vx = [0]
    for k in range(1, 5):
        lo = int(w * k / 5 - 35)
        hi = int(w * k / 5 + 35)
        vx.append(int(np.argmin(col_lum[lo:hi]) + lo))
    vx.append(w)

    hy = [0]
    for k in range(1, 3):
        lo = int(h * k / 3 - 35)
        hi = int(h * k / 3 + 35)
        hy.append(int(np.argmin(row_lum[lo:hi]) + lo))
    hy.append(h)

    cells: list[Image.Image] = []
    for r in range(3):
        for c in range(5):
            # Trim 6px inside black grid lines and 3px on outer sheet edges
            pad_l = 4 if c == 0 else 6
            pad_r = 4 if c == 4 else 6
            pad_t = 4 if r == 0 else 6
            pad_b = 4 if r == 2 else 6
            crop_box = (vx[c] + pad_l, hy[r] + pad_t, vx[c + 1] - pad_r, hy[r + 1] - pad_b)
            sub = im.crop(crop_box)
            # Center-crop slightly if needed to match target aspect cleanly without stretching
            sw, sh = sub.size
            tw, th = out_size
            target_ratio = tw / th
            cur_ratio = sw / sh
            if cur_ratio > target_ratio:
                new_w = int(sh * target_ratio)
                left = (sw - new_w) // 2
                sub = sub.crop((left, 0, left + new_w, sh))
            elif cur_ratio < target_ratio:
                new_h = int(sw / target_ratio)
                top = max(0, (sh - new_h) // 3)
                sub = sub.crop((0, top, sw, top + new_h))

            resized = sub.resize(out_size, Image.Resampling.LANCZOS)
            resized = ImageEnhance.Contrast(resized).enhance(1.04)
            resized = resized.filter(ImageFilter.UnsharpMask(radius=1.1, percent=95, threshold=2))
            cells.append(resized)
    return cells


