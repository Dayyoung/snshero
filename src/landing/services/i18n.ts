/**
 * src/landing/services/i18n.ts
 *
 * Universal 12-Language Internationalization (i18n) Engine for SNSHero.
 * Supports: ko, en, ja, zh-CN, zh-TW, de, es, fr, id, ru, th, vi.
 * Features instant reactive language switching, localStorage persistence ('hero_language'),
 * and full dictionary translation coverage across all UI views.
 */

export type SupportedLanguage =
  | 'ko'
  | 'en'
  | 'ja'
  | 'zh-CN'
  | 'zh-TW'
  | 'de'
  | 'es'
  | 'fr'
  | 'id'
  | 'ru'
  | 'th'
  | 'vi';

export const SUPPORTED_LANGUAGES: readonly SupportedLanguage[] = [
  'ko',
  'en',
  'ja',
  'zh-CN',
  'zh-TW',
  'de',
  'es',
  'fr',
  'id',
  'ru',
  'th',
  'vi',
] as const;

export function getCurrentLanguage(): SupportedLanguage {
  if (typeof localStorage === 'undefined') return 'ko';
  const saved = localStorage.getItem('hero_language') as SupportedLanguage | null;
  if (saved && (SUPPORTED_LANGUAGES as readonly string[]).includes(saved)) {
    return saved;
  }
  return 'ko';
}

export function setCurrentLanguage(lang: string): SupportedLanguage {
  const target: SupportedLanguage = (SUPPORTED_LANGUAGES as readonly string[]).includes(lang)
    ? (lang as SupportedLanguage)
    : 'ko';

  if (typeof localStorage !== 'undefined') {
    localStorage.setItem('hero_language', target);
  }

  if (typeof window !== 'undefined') {
    window.dispatchEvent(new CustomEvent('snshero_language_changed', { detail: { lang: target } }));
  }

  return target;
}

