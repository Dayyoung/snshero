export function getAllWebtoonEpisodes(): WebtoonEpisodeMeta[] {
  return WEBTOON_40_EPISODES;
}

export function getWebtoonEpisode(episodeNumber: number): WebtoonEpisodeMeta {
  const ep = WEBTOON_40_EPISODES.find((e) => e.episodeNumber === episodeNumber);
  if (ep) return ep;
  return WEBTOON_40_EPISODES[0];
}

export function getWebtoonSceneImageUrl(episodeNumber: number, sceneIndex: number): string {
  const padEp = String(episodeNumber).padStart(2, '0');
  const padScene = String(sceneIndex).padStart(2, '0');
  return `/images/webtoon/episode_${padEp}/scene_${padScene}.webp`;
}

export function getWebtoonCoverImageUrl(episodeNumber: number): string {
  const padEp = String(episodeNumber).padStart(2, '0');
  return `/images/webtoon/episode_${padEp}/scene_00.webp`;
}
